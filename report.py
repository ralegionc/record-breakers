"""Headline numbers from tables/*.csv -> tables/summary.md (quoted in the README)."""
import pandas as pd

from config import PRIMARY, TABLES

ML = ["GraphCast", "Pangu", "FuXi"]


def fmt(x, lo, hi, nd=3):
    return f"{x:+.{nd}f} [{lo:+.{nd}f}, {hi:+.{nd}f}]"


def main():
    freq = pd.read_csv(TABLES / "freq.csv")
    mat = pd.read_csv(TABLES / "matched.csv")
    frac = pd.read_csv(TABLES / "record_area_fraction.csv", index_col=0).iloc[:, 0]
    out = ["# Summary (generated by report.py)", ""]
    out.append(f"Share of 2020 area-time beyond the 1979-2019 record (+-15 days, same hour): "
               f"warm {100 * frac['hot_frac']:.2f}%, cold {100 * frac['cold_frac']:.3f}%.")
    out.append("")

    out.append("## Frequency ratio, forecast/observed, warm side, debiased")
    out.append("")
    out.append("| lead | model | z>3 | old record | record +0.5 sd |")
    out.append("|---|---|---|---|---|")
    f = freq[(freq.period == PRIMARY) & (freq.side == "hot") & (freq.variant == "debiased")]
    for L in [24, 72, 120]:
        for m in ["HRES"] + ML + ["HRES ceiling"]:
            q = f[(f.lead_h == L) & (f.model == m)].set_index("threshold").freq_ratio
            out.append(f"| day {L // 24} | {m} | {q['z>3.0']:.2f} | {q['record+0.0sd']:.2f} | {q['record+0.5sd']:.2f} |")
    out.append("")

    for v in ["debiased", "raw"]:
        out.append(f"## Matched test ({v}): extra error on records vs same-anomaly non-records, minus HRES (sd units, 95% CI)")
        out.append("")
        out.append("| side | lead | " + " | ".join(ML + ["shrunk 20% control", "ceiling control"]) + " |")
        out.append("|---|---|" + "---|" * 5)
        d = mat[(mat.period == PRIMARY) & (mat.variant == v) & (mat.unit == "sd")]
        for side in ["hot", "cold"]:
            for L in [24, 72, 120, 168, 240]:
                cells = []
                for m in ML + ["HRES shrunk 20%", "HRES ceiling"]:
                    r = d[(d.side == side) & (d.lead_h == L) & (d.model == m)].iloc[0]
                    cells.append(fmt(r.effect_minus_hres, r.emh_lo, r.emh_hi))
                out.append(f"| {side} | {L // 24}d | " + " | ".join(cells) + " |")
        out.append("")

    out.append("## ML effect as a share of the ceiling control (warm, debiased, days 1-5)")
    out.append("")
    d = mat[(mat.period == PRIMARY) & (mat.variant == "debiased") & (mat.unit == "sd") & (mat.side == "hot")]
    for L in [24, 72, 120]:
        c = d[(d.lead_h == L) & (d.model == "HRES ceiling")].effect_minus_hres.iloc[0]
        parts = [f"{m} {100 * d[(d.lead_h == L) & (d.model == m)].effect_minus_hres.iloc[0] / c:.0f}%" for m in ML]
        out.append(f"- day {L // 24}: " + ", ".join(parts))
    out.append("")

    out.append("## Sensitivity: record period (warm, debiased, day 3, sd)")
    out.append("")
    out.append("| period | " + " | ".join(ML) + " | ceiling control |")
    out.append("|---|---|---|---|---|")
    d = mat[(mat.variant == "debiased") & (mat.unit == "sd") & (mat.side == "hot") & (mat.lead_h == 72)]
    for p in ["1979-2019", "1979-2017", "1959-2019"]:
        cells = [fmt(*d[(d.period == p) & (d.model == m)][["effect_minus_hres", "emh_lo", "emh_hi"]].iloc[0])
                 for m in ML + ["HRES ceiling"]]
        out.append(f"| {p} | " + " | ".join(cells) + " |")
    out.append("")

    out.append("## Hit rate on record-warm steps (forecast also beyond the old record), debiased")
    out.append("")
    h = freq[(freq.period == PRIMARY) & (freq.side == "hot") & (freq.variant == "debiased") & (freq.threshold == "record+0.0sd")]
    for L in [24, 72, 120]:
        parts = [f"{m} {h[(h.lead_h == L) & (h.model == m)].hit_rate.iloc[0]:.2f}" for m in ["HRES"] + ML]
        out.append(f"- day {L // 24}: " + ", ".join(parts))
    (TABLES / "summary.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
